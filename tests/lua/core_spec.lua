local Core = require 'Core'
local json = require 'dkjson'

local function readFile(path)
  local f = assert(io.open(path, 'r'))
  local text = f:read('*a')
  f:close()
  return text
end

local contract = Core.decodeContract(readFile('src/batchlight_mcp/plugin/BatchLight.lrplugin/contract.json'))
local discovery = json.encode({ port = 50123, token = 'secret', pid = 1, protocol = 1, server_version = '0.1.0' })

describe('environment', function()
  it('matches Lightroom: Lua 5.1 without table.unpack', function()
    assert.are.equal('Lua 5.1', _VERSION)
    assert.is_nil(table.unpack)
  end)
end)

describe('parseDiscovery', function()
  it('reads the hub details', function()
    local info = Core.parseDiscovery(discovery)
    assert.are.equal('http://127.0.0.1:50123', info.baseUrl)
    assert.are.equal('secret', info.token)
  end)

  it('rejects missing, malformed and incomplete files', function()
    assert.is_nil(Core.parseDiscovery(nil))
    assert.is_nil(Core.parseDiscovery(''))
    assert.is_nil(Core.parseDiscovery('{not json'))
    assert.is_nil(Core.parseDiscovery(json.encode({ port = 1 })))
    assert.is_nil(Core.parseDiscovery(json.encode({ port = 1, token = '' })))
  end)

  it('refuses hubs started by the test suite', function()
    local info, reason = Core.parseDiscovery(json.encode({ port = 1, token = 't', test = true }))
    assert.is_nil(info)
    assert.are.equal('test_hub', reason)
  end)
end)

describe('backoff', function()
  it('doubles from 1 s and caps at 30 s', function()
    local seen = {}
    for failures = 1, 8 do seen[failures] = Core.backoff(failures) end
    assert.are.same({ 1, 2, 4, 8, 16, 30, 30, 30 }, seen)
    assert.are.equal(0, Core.backoff(0))
  end)
end)

describe('nextStep', function()
  it('waits while there is no hub, then says hello, then polls', function()
    local state = Core.newState()
    assert.are.same({ kind = 'wait', seconds = Core.FILE_CHECK_SECONDS }, Core.nextStep(state, nil, 0))
    assert.are.same({ kind = 'hello' }, Core.nextStep(state, discovery, 1))
    Core.onHello(state, 'ok', 1)
    assert.are.same({ kind = 'poll' }, Core.nextStep(state, discovery, 2))
  end)

  it('backs off after failures but keeps checking the file', function()
    local state = Core.newState()
    Core.nextStep(state, discovery, 0)
    Core.onHello(state, 'network', 0)
    Core.onHello(state, 'network', 0)
    Core.onHello(state, 'network', 0)  -- third failure: 4 s
    local step = Core.nextStep(state, discovery, 1)
    assert.are.equal('wait', step.kind)
    assert.is_true(step.seconds <= Core.FILE_CHECK_SECONDS)
    assert.are.same({ kind = 'hello' }, Core.nextStep(state, discovery, 4))
  end)

  it('retries at once when the discovery file changes', function()
    local state = Core.newState()
    Core.nextStep(state, discovery, 0)
    for _ = 1, 6 do Core.onHello(state, 'network', 0) end
    assert.are.equal('wait', Core.nextStep(state, discovery, 1).kind)
    local newHub = json.encode({ port = 50124, token = 'new' })
    assert.are.same({ kind = 'hello' }, Core.nextStep(state, newHub, 1))
    assert.are.equal(50124, state.info.port)
  end)

  it('goes back to waiting when the file disappears', function()
    local state = Core.newState()
    Core.nextStep(state, discovery, 0)
    Core.onHello(state, 'ok', 0)
    assert.are.equal('wait', Core.nextStep(state, nil, 1).kind)
    assert.is_false(state.connected)
  end)
end)

describe('onPoll', function()
  it('keeps polling on ok and idle', function()
    local state = Core.newState()
    Core.nextStep(state, discovery, 0)
    Core.onHello(state, 'ok', 0)
    Core.onPoll(state, 'idle', 1)
    Core.onPoll(state, 'ok', 1)
    assert.are.same({ kind = 'poll' }, Core.nextStep(state, discovery, 1))
  end)

  it('says hello again at once after stale or hello_required', function()
    for _, outcome in ipairs({ 'stale', 'hello_required' }) do
      local state = Core.newState()
      Core.nextStep(state, discovery, 0)
      Core.onHello(state, 'ok', 0)
      Core.onPoll(state, outcome, 1)
      assert.are.same({ kind = 'hello' }, Core.nextStep(state, discovery, 1))
    end
  end)

  it('backs off after a network failure or rejection', function()
    for _, outcome in ipairs({ 'network', 'rejected' }) do
      local state = Core.newState()
      Core.nextStep(state, discovery, 0)
      Core.onHello(state, 'ok', 0)
      Core.onPoll(state, outcome, 10)
      assert.are.equal(11, state.retryAt)
    end
  end)
end)

describe('describe', function()
  it('follows the loop from starting to connected', function()
    assert.matches('starting', Core.describe(nil))
    local state = Core.newState()
    Core.nextStep(state, nil, 0)
    assert.matches('Waiting for the BatchLight server', Core.describe(state))
    Core.nextStep(state, discovery, 1)
    assert.matches('Connecting', Core.describe(state))
    Core.onHello(state, 'ok', 1)
    assert.matches('Connected', Core.describe(state))
  end)

  it('reports a server that stopped answering', function()
    local state = Core.newState()
    Core.nextStep(state, discovery, 0)
    Core.onHello(state, 'network', 0)
    assert.matches('not answering', Core.describe(state))
  end)

  it('reports a discovery file it cannot use, such as a test hub', function()
    local state = Core.newState()
    Core.nextStep(state, json.encode({ port = 1, token = 't', test = true }), 0)
    assert.matches('cannot use', Core.describe(state))
  end)
end)

describe('classify', function()
  it('maps HTTP statuses to outcomes', function()
    assert.are.equal('network', Core.classify(nil))
    assert.are.equal('ok', Core.classify(200))
    assert.are.equal('idle', Core.classify(204))
    assert.are.equal('stale', Core.classify(409))
    assert.are.equal('hello_required', Core.classify(428))
    assert.are.equal('rejected', Core.classify(401))
    assert.are.equal('rejected', Core.classify(503))
  end)
end)

describe('commands', function()
  it('accepts the contract example command', function()
    assert.is_true(Core.validateCommand(contract.examples.command, contract.actions))
  end)

  it('rejects malformed commands and unknown actions with contract codes', function()
    local _, code = Core.validateCommand({ id = 'x' }, contract.actions)
    assert.are.equal('bad_request', code)
    _, code = Core.validateCommand({ id = 'x', action = 'status', params = 'nope' }, contract.actions)
    assert.are.equal('bad_request', code)
    _, code = Core.validateCommand({ id = 'x', action = 'delete_everything' }, contract.actions)
    assert.are.equal('unknown_action', code)
    assert.is_not_nil(contract.errors.bad_request)
    assert.is_not_nil(contract.errors.unknown_action)
  end)

  it('treats expiry as a start deadline, and trusts the hub without a clock', function()
    assert.is_true(Core.isExpired({ expires_at = 100 }, 101))
    assert.is_false(Core.isExpired({ expires_at = 100 }, 99))
    assert.is_false(Core.isExpired({ expires_at = 100 }, nil))
  end)

  it('builds replies shaped like the contract examples', function()
    local ok = Core.okReply('id1', 7, { a = 1 })
    for key in pairs(contract.examples.result_ok) do assert.is_not_nil(ok[key], key) end
    local err = Core.errorReply('id1', 7, 'handler_failed', { action = 'status' })
    for key in pairs(contract.examples.result_error) do assert.is_not_nil(err[key], key) end
    assert.is_not_nil(contract.errors[err.error.code])
  end)
end)

describe('result cache', function()
  it('answers a repeated delivery from the cache', function()
    local cache = Core.newCache(3)
    Core.cachePut(cache, 'a', 'reply-a')
    assert.are.equal('reply-a', Core.cacheGet(cache, 'a'))
  end)

  it('keeps only the newest entries', function()
    local cache = Core.newCache(2)
    Core.cachePut(cache, 'a', 1)
    Core.cachePut(cache, 'b', 2)
    Core.cachePut(cache, 'c', 3)
    assert.is_nil(Core.cacheGet(cache, 'a'))
    assert.are.equal(2, Core.cacheGet(cache, 'b'))
    assert.are.equal(3, Core.cacheGet(cache, 'c'))
    assert.are.equal(2, #cache.order)
  end)
end)
